CREATE TABLE IF NOT EXISTS calculator_gate_settings (
  id TINYINT UNSIGNED NOT NULL PRIMARY KEY DEFAULT 1,
  gate_enabled TINYINT(1) NOT NULL DEFAULT 0,
  trigger_value DECIMAL(18, 6) NOT NULL DEFAULT 16,
  unlock_action VARCHAR(32) NOT NULL DEFAULT 'app',
  allow_add TINYINT(1) NOT NULL DEFAULT 1,
  allow_sub TINYINT(1) NOT NULL DEFAULT 1,
  allow_mul TINYINT(1) NOT NULL DEFAULT 0,
  allow_div TINYINT(1) NOT NULL DEFAULT 0,
  max_attempts SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  lock_minutes SMALLINT UNSIGNED NOT NULL DEFAULT 5,
  show_on_resume TINYINT(1) NOT NULL DEFAULT 1,
  superadmin_only TINYINT(1) NOT NULL DEFAULT 0,
  visual_theme VARCHAR(32) NOT NULL DEFAULT 'neon',
  display_mode VARCHAR(32) NOT NULL DEFAULT 'fullscreen',
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

